"""Convert an Aurora mysqldump file into a psql data-load script.

Usage:
    python mysqldump_to_pg.py Dump20261030.sql aurora_data.sql
    psql -v ON_ERROR_STOP=1 -U aurora -d aurora -f aurora_data.sql

The target database must already have the tables from V1__initial_schema.sql. The generated
script runs in a single transaction: it loads every table with COPY, moves each
identity sequence past MySQL's AUTO_INCREMENT value, and then checks row counts
and the sum of every decimal column against what was read from the dump. Any
mismatch raises an error and the whole load is rolled back.

Only the standard library is used; the dump is streamed, not loaded into memory.
"""

import re
import sys
from decimal import Decimal

CREATE_RE = re.compile(r"^CREATE TABLE `(\w+)` \(")
COLUMN_RE = re.compile(r"^  `(\w+)` (\w+)(\([^)]*\))?")
PK_RE = re.compile(r"^  PRIMARY KEY \(`(\w+)`\)")
AUTO_INC_RE = re.compile(r"AUTO_INCREMENT=(\d+)")
INSERT_RE = re.compile(r"^INSERT INTO `(\w+)`(?: \(([^)]*)\))? VALUES ")

MYSQL_ESCAPES = {"0": "\0", "b": "\b", "n": "\n", "r": "\r", "t": "\t",
                 "Z": "\x1a", "\\": "\\", "'": "'", '"': '"'}


class Table:
    def __init__(self, name):
        self.name = name
        self.columns = []      # column names in MySQL order
        self.types = {}        # column -> (mysql type, length spec)
        self.pk = None
        self.auto_increment = None
        self.rows = 0
        self.sums = {}         # decimal column -> Decimal total

    def is_boolean(self, col):
        return self.types[col] == ("bit", "(1)")

    def is_decimal(self, col):
        return self.types[col][0] == "decimal"


def parse_values(text, pos):
    """Yield one list of raw values per tuple in an extended INSERT, starting at text[pos]."""
    n = len(text)
    while pos < n:
        if text[pos] != "(":
            raise ValueError("expected '(' at offset %d: %r" % (pos, text[pos:pos + 40]))
        pos += 1
        row = []
        while True:
            c = text[pos]
            if c == "'" or text.startswith("_binary '", pos):
                binary = c != "'"
                if binary:
                    pos += len("_binary ")
                pos += 1
                buf = []
                while True:
                    c = text[pos]
                    if c == "\\":
                        buf.append(MYSQL_ESCAPES.get(text[pos + 1], text[pos + 1]))
                        pos += 2
                    elif c == "'":
                        if text.startswith("''", pos):
                            buf.append("'")
                            pos += 2
                        else:
                            pos += 1
                            break
                    else:
                        buf.append(c)
                        pos += 1
                row.append(("bin" if binary else "str", "".join(buf)))
            else:
                end = pos
                while text[end] not in ",)":
                    end += 1
                token = text[pos:end]
                row.append(("null", None) if token == "NULL" else ("num", token))
                pos = end
            if text[pos] == ",":
                pos += 1
                continue
            pos += 1  # ')'
            break
        yield row
        if pos < n and text[pos] == ",":
            pos += 1
        elif pos < n and text[pos] == ";":
            return


def copy_escape(value):
    return (value.replace("\\", "\\\\").replace("\t", "\\t")
            .replace("\n", "\\n").replace("\r", "\\r"))


def to_copy_field(table, col, kind, value):
    if kind == "null":
        return "\\N"
    if table.is_boolean(col):
        if kind == "bin":
            return "t" if value and value != "\0" else "f"
        return "t" if value not in ("0", "b'0'") else "f"
    if "\0" in (value or ""):
        raise ValueError("NUL byte in %s.%s cannot be stored in PostgreSQL" % (table.name, col))
    if table.is_decimal(col):
        table.sums[col] += Decimal(value)
    return copy_escape(value)


def convert(dump_path, out_path):
    tables = {}
    order = []
    current = None   # table whose CREATE TABLE is being read
    copying = None   # table whose COPY block is open

    with open(dump_path, encoding="utf-8", newline="") as src, \
            open(out_path, "w", encoding="utf-8", newline="\n") as out:
        out.write("-- Generated by mysqldump_to_pg.py from %s\n" % dump_path.replace("\\", "/").split("/")[-1])
        out.write("\\set ON_ERROR_STOP on\nSET client_encoding = 'UTF8';\nBEGIN;\n")

        for line in src:
            line = line.rstrip("\r\n")

            if current is not None:
                m = COLUMN_RE.match(line)
                if m:
                    current.columns.append(m.group(1))
                    current.types[m.group(1)] = (m.group(2).lower(), m.group(3) or "")
                    continue
                m = PK_RE.match(line)
                if m:
                    current.pk = m.group(1)
                    continue
                if line.startswith(")"):
                    m = AUTO_INC_RE.search(line)
                    current.auto_increment = int(m.group(1)) if m else None
                    current.sums = {c: Decimal(0) for c in current.columns if current.is_decimal(c)}
                    current = None
                continue

            m = CREATE_RE.match(line)
            if m:
                current = tables[m.group(1)] = Table(m.group(1))
                order.append(current)
                continue

            m = INSERT_RE.match(line)
            if not m:
                continue
            table = tables[m.group(1)]
            columns = ([c.strip(" `") for c in m.group(2).split(",")] if m.group(2) else table.columns)
            if copying is not table:
                if copying is not None:
                    out.write("\\.\n")
                out.write("COPY %s (%s) FROM stdin;\n" % (table.name, ", ".join(columns)))
                copying = table
            for row in parse_values(line, m.end()):
                if len(row) != len(columns):
                    raise ValueError("%s: expected %d values, got %d" % (table.name, len(columns), len(row)))
                out.write("\t".join(to_copy_field(table, c, k, v) for c, (k, v) in zip(columns, row)))
                out.write("\n")
                table.rows += 1

        if copying is not None:
            out.write("\\.\n")

        for t in order:
            if t.pk:
                floor = (t.auto_increment - 1) if t.auto_increment else 0
                out.write("SELECT setval(pg_get_serial_sequence('%s', '%s'), "
                          "GREATEST(COALESCE((SELECT max(%s) FROM %s), 0), %d, 1));\n"
                          % (t.name, t.pk, t.pk, t.name, floor))

        out.write("DO $$\nBEGIN\n")
        for t in order:
            out.write("  IF (SELECT count(*) FROM %s) <> %d THEN RAISE EXCEPTION "
                      "'%s: row count mismatch'; END IF;\n" % (t.name, t.rows, t.name))
            for col, total in t.sums.items():
                out.write("  IF (SELECT COALESCE(sum(%s), 0) FROM %s) <> %s THEN RAISE EXCEPTION "
                          "'%s.%s: sum mismatch'; END IF;\n" % (col, t.name, total, t.name, col))
        out.write("END $$;\nCOMMIT;\n")
        # Fresh statistics so the planner picks the right indexes from the first request.
        out.write("ANALYZE;\n")

    for t in order:
        sums = ", ".join("%s=%s" % (c, s) for c, s in t.sums.items())
        print("%-15s %9d rows  %s" % (t.name, t.rows, sums))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    convert(sys.argv[1], sys.argv[2])
