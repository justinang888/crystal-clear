-- Aurora schema for PostgreSQL (10+).
-- Mirrors the MySQL schema column-for-column so a mysqldump can be loaded into it
-- with mysqldump_to_pg.py. Run as the database owner:
--   psql -v ON_ERROR_STOP=1 -U aurora -d aurora -f schema.sql
--
-- Type mapping from MySQL: int/bigint AUTO_INCREMENT -> identity, decimal -> numeric,
-- datetime -> timestamp (no time zone; values are Asia/Manila wall-clock time),
-- bit(1) -> boolean.

CREATE TABLE ar_summary (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ar_amount   numeric(19,2),
  customer_id bigint NOT NULL,
  updated_at  timestamp(6)
);

CREATE TABLE container (
  container_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  integer NOT NULL,
  order_id     integer,
  status       varchar(45) NOT NULL,
  round_count  integer,
  slim_count   integer,
  created_at   timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

CREATE TABLE customer (
  customer_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type             varchar(45) NOT NULL,
  name             varchar(45) NOT NULL,
  address          varchar(255),
  contact_name     varchar(45),
  main_number      varchar(45),
  alternate_number varchar(45),
  email_address    varchar(45),
  order_interval   integer,
  total_round      integer NOT NULL DEFAULT 0,
  total_slim       integer NOT NULL DEFAULT 0
);
COMMENT ON TABLE customer IS 'Customer details';

CREATE TABLE customer_price (
  price_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id   integer NOT NULL,
  product_id    integer NOT NULL,
  selling_price numeric(10,2) NOT NULL,
  created_at    timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at    timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

CREATE TABLE debt (
  debt_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id     integer NOT NULL,
  amount          numeric(10,2) NOT NULL,
  remarks         varchar(255),
  created_at      timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  linked_order_id integer
);

CREATE TABLE expense (
  expense_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  amount      numeric(10,2) NOT NULL,
  description varchar(45) NOT NULL,
  created_at  timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

CREATE TABLE order_product (
  order_product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id         integer NOT NULL,
  product_id       integer NOT NULL,
  quantity         integer NOT NULL
);

CREATE TABLE orders (
  order_id                          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id                       integer NOT NULL,
  delivery_receipt_num              varchar(45) NOT NULL,
  status                            varchar(45) NOT NULL,
  amount_paid                       numeric(10,2) NOT NULL,
  total_amount                      numeric(10,2) NOT NULL,
  slim_refill_only_count            integer NOT NULL DEFAULT 0,
  round_refill_only_count           integer NOT NULL DEFAULT 0,
  slim_container_only_count         integer NOT NULL DEFAULT 0,
  round_container_only_count        integer NOT NULL DEFAULT 0,
  slim_refill_with_container_count  integer NOT NULL DEFAULT 0,
  round_refill_with_container_count integer NOT NULL DEFAULT 0,
  slim_free_count                   integer NOT NULL,
  round_free_count                  integer NOT NULL,
  cont_slim_returned                integer NOT NULL DEFAULT 0,
  cont_round_returned               integer NOT NULL DEFAULT 0,
  created_at                        timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  remarks                           varchar(500)
);

CREATE TABLE payment (
  payment_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id  integer NOT NULL,
  amount       numeric(10,2) NOT NULL,
  wh_tax       numeric(10,2) NOT NULL DEFAULT 0.00,
  payment_type varchar(45) NOT NULL DEFAULT 'CASH',
  remarks      varchar(45),
  created_at   timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

CREATE TABLE products (
  product_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          varchar(45) NOT NULL,
  description   varchar(100),
  initial_price numeric(10,2) NOT NULL,
  selling_price numeric(10,2) NOT NULL,
  created_at    timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
  updated_at    timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
);

CREATE TABLE users (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      varchar(255),
  enabled    boolean NOT NULL,
  first_name varchar(255),
  last_name  varchar(255),
  password   varchar(60) NOT NULL,
  role       varchar(255),
  username   varchar(45) NOT NULL
);
-- MySQL compared usernames case-insensitively; keep "Admin" and "admin" from coexisting.
CREATE UNIQUE INDEX users_username_ci_key ON users (lower(username));

-- Lookup indexes for the app's per-customer, per-order and per-day queries
-- (the MySQL schema had none beyond the primary keys).
CREATE INDEX ar_summary_customer_id_idx     ON ar_summary (customer_id);
CREATE INDEX container_customer_id_idx      ON container (customer_id);
CREATE INDEX container_created_at_idx       ON container (created_at);
CREATE INDEX customer_price_customer_id_idx ON customer_price (customer_id);
CREATE INDEX customer_price_product_id_idx  ON customer_price (product_id);
CREATE INDEX debt_customer_id_idx           ON debt (customer_id, linked_order_id);
CREATE INDEX expense_created_at_idx         ON expense (created_at);
CREATE INDEX order_product_order_id_idx     ON order_product (order_id);
CREATE INDEX orders_customer_id_idx         ON orders (customer_id, created_at);
CREATE INDEX orders_created_at_idx          ON orders (created_at);
CREATE INDEX orders_status_idx              ON orders (status);
CREATE INDEX payment_customer_id_idx        ON payment (customer_id, created_at);
CREATE INDEX payment_created_at_idx         ON payment (created_at);
