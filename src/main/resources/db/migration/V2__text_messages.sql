-- Text reminders to inactive customers (docs/specs/sms-inactive-customers.md).
-- Only adds: the old WAR ignores the new column and table, so rolling back stays a WAR swap.

-- A customer who asked not to be texted. Changed only from its own switch on the customer page,
-- never by the customer forms, which post a whole customer.
ALTER TABLE customer ADD COLUMN sms_opt_out boolean NOT NULL DEFAULT false;

-- Every text Aurora asked the phone to send, sent or not.
CREATE TABLE sms_message (
  sms_message_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id    integer     NOT NULL REFERENCES customer (customer_id),
  phone_number   varchar(20) NOT NULL,  -- as sent: +639XXXXXXXXX
  body           text        NOT NULL,
  state          varchar(20) NOT NULL,  -- the phone's state (Pending, Processed, Sent, Delivered, Failed) or Error
  gateway_id     varchar(64),           -- the phone's id for the message, when it gave one
  error          text,                  -- why it was not sent, when it was not
  created_at     timestamp   NOT NULL DEFAULT now(),
  created_by     varchar(50) NOT NULL   -- the Aurora user who clicked Send
);

CREATE INDEX sms_message_customer_created_idx ON sms_message (customer_id, created_at);
